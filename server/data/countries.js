/**
 * The flag emoji for a code, built from the two regional-indicator letters
 * rather than stored — 249 pasted emoji would be 249 chances to paste the wrong
 * one, and every platform already renders the pair.
 */
const flagOf = (code) =>
  String.fromCodePoint(...String(code).toUpperCase().split('').map(c => 0x1f1a5 + c.charCodeAt(0)));

const COUNTRIES = ROWS.map(([code, name]) => ({
  code,
  name,
  flag: flagOf(code),
  aliases: ALIASES[code] || [],
}));

const BY_CODE = new Map(COUNTRIES.map(c => [c.code, c]));

/** Normalise anything a caller offers to a valid code, or null. Accepts a name. */
function normalise(value) {
  const s = String(value == null ? '' : value).trim();
  if (!s) return null;
  const up = s.toUpperCase();
  if (BY_CODE.has(up)) return up;
  const lower = s.toLowerCase();
  const hit = COUNTRIES.find(c =>
    c.name.toLowerCase() === lower || c.aliases.some(a => a.toLowerCase() === lower));
  return hit ? hit.code : null;
}

const isValid = (code) => BY_CODE.has(String(code || '').toUpperCase());
const get     = (code) => BY_CODE.get(String(code || '').toUpperCase()) || null;
const nameOf  = (code) => get(code)?.name || null;

module.exports = { COUNTRIES, BY_CODE, flagOf, normalise, isValid, get, nameOf };
